#!/usr/bin/env python3
"""Generate the customer portal's static pages from content/*.py.

    python3 tools/build_site.py

Each section module in content/ exports `content`: one section's HTML (plus its
own <style>/<script>). This script wraps every section in the shared page shell
(nav, search, language dialog, footer) and writes it to its own URL:

    site/customer/index.html               <- content/welcome.py
    site/customer/products/index.html      <- content/products.py
    ...
    site/customer/search-index.json        <- headings + item titles, for search

The output is GENERATED - edit content/*.py or the shell below, then rebuild.
deploy.sh runs this automatically before every deploy. Everything under
/customer/ (pages AND the search index) is gated by functions/customer/_middleware.js.
"""
import hashlib
import html as htmllib
import importlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
sys.path.insert(0, str(ROOT / "content"))

# (id used by switchTab, module, URL, nav label, eyebrow, icon)
SECTIONS = [
    ("welcome", "welcome", "/customer/", "Welcome", "Start here", "fa-house"),
    ("products", "products", "/customer/products/", "My Products", "Your hardware", "fa-box-open"),
    ("installation", "installation", "/customer/installation/", "Installation", "Get vehicles online", "fa-screwdriver-wrench"),
    ("platform", "platform_tutorials", "/customer/platform/", "Platform Tutorials", "Learn the platform", "fa-display"),
    ("ai-features", "ai_features", "/customer/ai-features/", "AI Features", "AI safety", "fa-brain"),
    ("training", "training_academy", "/customer/training/", "Training Academy", "Team enablement", "fa-graduation-cap"),
    ("playbooks", "playbooks", "/customer/playbooks/", "Playbooks", "Run the programme", "fa-book-open"),
    ("support", "support", "/customer/support/", "Support", "Get help", "fa-life-ring"),
]
ROUTE = {s[0]: s[2] for s in SECTIONS}

GENERATED_NOTE = "<!-- GENERATED by tools/build_site.py from content/*.py - do not edit by hand. -->"

# Item titles worth finding by name, beyond h2-h4 headings.
SEARCH_ITEM_CLASSES = ("product-name", "inst-prod-name", "aif-feat-name", "pfn-name", "video-title")


def asset_version(rel: str) -> str:
    """Short content hash for cache-busting (?v=...)."""
    return hashlib.sha1((SITE / rel.lstrip("/")).read_bytes()).hexdigest()[:10]


def strip_tags(s: str) -> str:
    s = re.sub(r"<(style|script)\b.*?</\1>", " ", s, flags=re.S)
    s = re.sub(r"<[^>]+>", " ", s)
    return re.sub(r"\s+", " ", htmllib.unescape(s)).strip()


def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:60] or "section"


def rewrite_nav_links(html: str) -> str:
    """href="javascript:void(0)" onclick="switchTab('x')" -> real href. Real links fix
    back/refresh/middle-click and the Chrome/Windows javascript:void(0) failure."""
    def repl(m):
        url = ROUTE.get(m.group(1))
        if not url:
            raise SystemExit(f"build_site: unknown switchTab target {m.group(1)!r}")
        return f'href="{url}"'
    return re.sub(r'href="javascript:void\(0\)"\s+onclick="switchTab\(\'([a-z-]+)\'\)"', repl, html)


def promote_page_title(html: str, eyebrow: str) -> str:
    """The first <h2> of a section page is its title: make it the page's only <h1>
    (heading hierarchy) and put the eyebrow above it."""
    m = re.search(r"<h2(\s[^>]*)?>(.*?)</h2>", html, flags=re.S)
    if not m:
        return html
    h1 = f'<p class="page-eyebrow">{eyebrow}</p><h1 class="page-title">{m.group(2)}</h1>'
    return html[: m.start()] + h1 + html[m.end():]


def excluded_spans(html: str):
    """Regions not indexed for search (the FleetMind simulator's own UI)."""
    spans = []
    for m in re.finditer(r"<!-- simulator -->(.*?)<!-- /simulator -->", html, flags=re.S):
        spans.append((m.start(), m.end()))
    for m in re.finditer(r'<section class="stmx-brand-morph".*?</section>', html, flags=re.S):
        spans.append((m.start(), m.end()))  # the Welcome particle band (decorative copy)
    return spans


def add_anchors_and_index(html: str, sid: str, label: str, url: str, icon: str):
    """Give every heading / item title an id (if it lacks one) and collect search entries."""
    entries = []
    used = set(re.findall(r'\sid="([^"]+)"', html))
    skip = excluded_spans(html)
    item_re = "|".join(SEARCH_ITEM_CLASSES)
    pattern = re.compile(
        r'<(h[1-4])(\s[^>]*)?>(.*?)</\1>'
        r'|<(span|div|strong)(\s[^>]*class="[^"]*\b(?:' + item_re + r')\b[^"]*"[^>]*)>(.*?)</\4>',
        flags=re.S,
    )
    out, pos = [], 0
    for m in pattern.finditer(html):
        if any(a <= m.start() < b for a, b in skip):
            continue
        tag = m.group(1) or m.group(4)
        attrs = (m.group(2) if m.group(1) else m.group(5)) or ""
        inner = m.group(3) if m.group(1) else m.group(6)
        title = strip_tags(inner)
        if not title or len(title) < 3:
            continue
        idm = re.search(r'\sid="([^"]+)"', attrs)
        if idm:
            anchor = idm.group(1)
            new_open = f"<{tag}{attrs}>"
        else:
            base = slugify(title)
            anchor, n = base, 2
            while anchor in used:
                anchor, n = f"{base}-{n}", n + 1
            used.add(anchor)
            new_open = f'<{tag} id="{anchor}"{attrs}>'
        out.append(html[pos:m.start()])
        out.append(new_open + inner + f"</{tag}>")
        pos = m.end()
        snippet = strip_tags(html[m.end(): m.end() + 900])[:160]
        entries.append({
            "t": title[:120],
            "s": label,
            "u": url if tag == "h1" else f"{url}#{anchor}",
            "x": snippet,
            "i": icon,
        })
    out.append(html[pos:])
    return "".join(out), entries


