def build() -> int:
    v = {
        "stx": asset_version("/assets/css/stx.css"),
        "portal_css": asset_version("/assets/css/portal.css"),
        "portal_js": asset_version("/assets/js/portal.js"),
    }
    morph_v = asset_version("/assets/morph/truck-to-logo.html")
    index = []
    for i, (sid, module, url, label, eyebrow, icon) in enumerate(SECTIONS):
        html = importlib.import_module(module).content
        html = html.replace('class="content-section hidden"', 'class="content-section"')
        html = rewrite_nav_links(html)
        if sid == "welcome":
            # Extensionless: Pages 308-redirects *.html, which would drop the ?v= cache-buster.
            html = html.replace("__TRUCK_TO_LOGO_SRC__", f"/assets/morph/truck-to-logo?v={morph_v}")
            html = html.replace(
                "__KEY_CONTACTS__",
                '<tbody data-slot="contacts"><tr><td colspan="2">Loading your Streamax team...</td></tr></tbody>',
            )
        else:
            html = promote_page_title(html, eyebrow)
        html, entries = add_anchors_and_index(html, sid, label, url, icon)
        index.append({"t": label, "s": "Portal section", "u": url, "x": eyebrow, "i": icon})
        index.extend(e for e in entries if e["t"].lower() != label.lower())
        left = sorted(set(re.findall(r"__[A-Z][A-Z_]+__", html)))
        if left:
            raise SystemExit(f"build_site: unresolved placeholders in {module}: {left}")
        if "javascript:void" in html:
            raise SystemExit(f"build_site: javascript:void link left in {module}")
        out = SITE / url.lstrip("/") / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page_html(sid, label, html, i, v), encoding="utf-8")
        print(f"  {url:28s} <- content/{module}.py  ({out.stat().st_size // 1024} KB, {len(entries)} search entries)")
    (SITE / "customer" / "search-index.json").write_text(
        json.dumps(index, ensure_ascii=False, separators=(",", ":")), encoding="utf-8"
    )
    print(f"  /customer/search-index.json  ({len(index)} entries)")
    return len(SECTIONS)


if __name__ == "__main__":
    n = build()
    print(f"build_site: wrote {n} customer pages")
