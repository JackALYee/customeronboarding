def pager_html(index: int) -> str:
    prev_s = SECTIONS[index - 1] if index > 0 else None
    next_s = SECTIONS[index + 1] if index + 1 < len(SECTIONS) else None
    def card(s, rel):
        if not s:
            return "<span></span>"
        arrow_l = '<i class="fa-solid fa-arrow-left" aria-hidden="true"></i>' if rel == "prev" else ""
        arrow_r = '<i class="fa-solid fa-arrow-right" aria-hidden="true"></i>' if rel == "next" else ""
        cap = "Previous" if rel == "prev" else "Next"
        return (f'<a class="pager-link pager-{rel}" href="{s[2]}" rel="{rel}">'
                f'<span class="pager-cap">{arrow_l}{cap}</span><span class="pager-title">{s[3]}</span>{arrow_r}</a>')
    return f'<nav class="pager" aria-label="Previous and next section">{card(prev_s, "prev")}{card(next_s, "next")}</nav>'


